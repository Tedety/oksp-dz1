CREATE SCHEMA IF NOT EXISTS stanislav_tedety;
SET search_path TO stanislav_tedety;

CREATE TABLE IF NOT EXISTS specialists (
    id integer PRIMARY KEY,
    name text NOT NULL
);
CREATE TABLE IF NOT EXISTS services (
    id integer PRIMARY KEY,
    name text NOT NULL,
    minutes integer NOT NULL CHECK (minutes > 0)
);
CREATE TABLE IF NOT EXISTS slots (
    id integer PRIMARY KEY,
    specialist_id integer NOT NULL REFERENCES specialists,
    starts_at timestamp NOT NULL,
    ends_at timestamp NOT NULL CHECK (ends_at > starts_at)
);
CREATE TABLE IF NOT EXISTS appointments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id integer NOT NULL REFERENCES slots,
    service_id integer NOT NULL REFERENCES services,
    status text NOT NULL CHECK (status IN ('booked','cancelled'))
);
